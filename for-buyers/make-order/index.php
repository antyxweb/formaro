<p class="lead">Formaro — маркетплейс: товары продают разные продавцы, а оформить заказ у нескольких из них можно за один раз в общей корзине.</p>

<h2>1. Войдите на сайт</h2>
<p>Заказы оформляют зарегистрированные покупатели. Войдите или зарегистрируйтесь — логином служит ваш e-mail. Контакты и реквизиты (для юридических лиц и ИП) можно заранее заполнить в разделе «<a href="/personal/profile/">Ваш профиль</a>».</p>

<h2>2. Добавьте товары в корзину</h2>
<p>Выберите товар в <a href="/catalog/">каталоге</a>, укажите нужное количество и нажмите «В корзину». Если остались вопросы о товаре, нажмите «Чат с продавцом» в карточке товара — продавец ответит в разделе «<a href="/personal/messages/">Чаты и сообщения</a>».</p>

<h2>3. Проверьте корзину</h2>
<p>В <a href="/personal/cart/">корзине</a> товары сгруппированы по продавцам. Флажками отметьте товары, которые оформляете сейчас, — остальные останутся в корзине до следующего раза. Если у вас есть промокод продавца, введите его: промокоды действуют на товары своего продавца, для каждого продавца можно применить свой.</p>

<h2>4. Заполните данные заказа</h2>
<ul>
    <li><strong>Способ доставки</strong> — выберите транспортную компанию: СДЭК, Деловые линии, ПЭК или другую. Подробнее — в разделе «<a href="/for-buyers/delivery/">Доставка и стоимость</a>».</li>
    <li><strong>Данные покупателя</strong> — ФИО, телефон, e-mail и адрес доставки. Поля заполняются автоматически из вашего профиля и прошлых заказов — проверьте их. В комментарии можно оставить пожелания продавцу.</li>
    <li><strong>Способ оплаты</strong> — по счёту. Подробнее — в разделе «<a href="/for-buyers/payment/">Способ оплаты</a>».</li>
</ul>

<h2>5. Оформите заказ</h2>
<p>Нажмите «Оформить заказ». Если в корзине товары нескольких продавцов, на каждого продавца создаётся отдельный заказ — продавцы получат их и свяжутся с вами для подтверждения.</p>

<h2>6. Следите за заказом</h2>
<p>Все заказы — в разделе «<a href="/personal/orders/">Ваши заказы</a>» кабинета покупателя. Там можно:</p>
<ul>
    <li>видеть статус заказа и его историю;</li>
    <li>скачать счёт на оплату и сообщить об оплате;</li>
    <li>написать продавцу по заказу — «Чат с продавцом»;</li>
    <li>отменить заказ, пока он в статусе «Новый».</li>
</ul>
<p>О смене статуса, подтверждении оплаты и ответах продавца мы сообщим в разделе «<a href="/personal/notify/">Уведомления</a>».</p>
